import { openPage, outDir } from '/Users/admin/workspace/dsh-process-kit-example/e2e/uat-feat002/lib-cdp.mjs';
const B='http://127.0.0.1:3000';
const p=await openPage({width:390,height:844,dsf:2,mobile:true});
await p.send('Network.enable',{},p.sid);
const E=(x)=>p.eval(x);
const ck=async()=>{const r=await p.send('Network.getCookies',{urls:[B+'/']},p.sid);return (r.result.cookies||[]).map(c=>c.name+'='+c.value.slice(0,10)+'…(len'+c.value.length+') httpOnly:'+c.httpOnly+' sameSite:'+c.sameSite+' path:'+c.path+' secure:'+c.secure).join(' ; ')||'(无 cookie)';};
const R={};
R.初始=await ck();
await p.navigate(B+'/',3000);
R.首页后=await ck();
await p.navigate(B+'/#/products/P-002',2600);
R.详情后=await ck();
await p.eval(`(()=>{const b=[...document.querySelectorAll('button')].find(x=>/加入购物车/.test(x.innerText));b.click();return 1;})()`);
await p.wait(1500);
R.加购后=await ck();
R.加购后按钮文案=await E(`[...document.querySelectorAll('button')].map(x=>x.innerText.trim()).join('|')`);
R.加购后页脚=await E(`(()=>{const t=(document.body.innerText||'').replace(/\\n+/g,' | ');return t.slice(0,220);})()`);
await p.navigate(B+'/#/cart',2600);
R.购物车后=await ck();
R.购物车文本=await E(`(document.body.innerText||'').replace(/\\n+/g,' | ').slice(0,300)`);
R.购物车hash=await E(`location.hash`);
await p.navigate(B+'/#/checkout',2600);
R.结算文本=await E(`(document.body.innerText||'').replace(/\\n+/g,' | ').slice(0,360)`);
R.结算hash=await E(`location.hash`);
await p.navigate(B+'/#/cart',2600);
R.二回购物车文本=await E(`(document.body.innerText||'').replace(/\\n+/g,' | ').slice(0,300)`);
console.log(JSON.stringify(R,null,1));
await p.shot(outDir('r5-cart-cookie-购物车.png'));
await p.close();
