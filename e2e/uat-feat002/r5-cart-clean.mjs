await p.navigate(B+'/#/cart',2600); await note('6 购物车（两件？）');
const cartReqs=p.events.filter(e=>e.method==='Network.requestWillBeSent'&&/\/api\/v1\/cart/.test(e.params.request.url)).map(e=>({url:e.params.request.url,method:e.params.request.method,hasCookie:!!(e.params.request.headers.Cookie||e.params.request.headers.cookie),extraHeaders:Object.keys(e.params.request.headers).filter(k=>/cart|sid|auth/i.test(k))}));
